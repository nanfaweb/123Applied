// @ts-expect-error: Deno is available in the Edge Function runtime
Deno.serve(async (req: Request) => {
  // Check for Supabase JWT in Authorization header
  const authHeader = req.headers.get("Authorization");
  if (!authHeader || !authHeader.startsWith("Bearer ")) {
    return new Response(JSON.stringify({ error: "Missing or invalid Authorization header" }), {
      status: 401,
      headers: { "Content-Type": "application/json" },
    });
  }

  // @ts-expect-error: Supabase global is available in Edge Functions
  const { user, error } = await supabase.auth.getUser(req);
  if (error || !user) {
    return new Response(JSON.stringify({ error: "Unauthorized" }), {
      status: 401,
      headers: { "Content-Type": "application/json" },
    });
  }

  const { name } = await req.json();
  const data = {
    message: `Hello ${name}!`,
    user_id: user.id,
    email: user.email,
  };

  return new Response(
    JSON.stringify(data),
    { headers: { "Content-Type": "application/json" } },
  );
})

